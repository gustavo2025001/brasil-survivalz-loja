create table if not exists public.bs_admins (user_id uuid primary key references auth.users(id) on delete cascade, created_at timestamptz default now());
alter table public.bs_admins enable row level security;

create or replace function public.bs_is_admin() returns boolean language sql security definer set search_path=public stable as $$
  select exists(select 1 from public.bs_admins where user_id=auth.uid());
$$;
grant execute on function public.bs_is_admin() to authenticated;

create or replace function public.bs_admin_profiles() returns setof public.profiles language plpgsql security definer set search_path=public as $$
begin
 if not public.bs_is_admin() then raise exception 'Acesso negado'; end if;
 return query select * from public.profiles order by created_at desc nulls last;
end $$;
grant execute on function public.bs_admin_profiles() to authenticated;

-- Retorna pedidos como JSON para tolerar diferenças de colunas na tabela orders.
create or replace function public.bs_admin_orders() returns setof jsonb language plpgsql security definer set search_path=public as $$
begin
 if not public.bs_is_admin() then raise exception 'Acesso negado'; end if;
 return query select to_jsonb(o) from public.orders o order by o.created_at desc nulls last;
end $$;
grant execute on function public.bs_admin_orders() to authenticated;

create or replace function public.bs_admin_adjust_coins(p_user_id uuid,p_amount bigint,p_reason text default 'Ajuste manual') returns bigint language plpgsql security definer set search_path=public as $$
declare new_balance bigint;
begin
 if not public.bs_is_admin() then raise exception 'Acesso negado'; end if;
 update public.profiles set bs_coins=greatest(0,coalesce(bs_coins,0)+p_amount) where user_id=p_user_id returning bs_coins into new_balance;
 if new_balance is null then raise exception 'Jogador não encontrado'; end if;
 return new_balance;
end $$;
grant execute on function public.bs_admin_adjust_coins(uuid,bigint,text) to authenticated;

