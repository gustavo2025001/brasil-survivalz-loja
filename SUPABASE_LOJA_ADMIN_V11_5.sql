create or replace function public.bs_admin_adjust_coins(p_user_id uuid,p_amount bigint,p_reason text default 'Ajuste manual') returns bigint language plpgsql security definer set search_path=public as $$ declare b bigint; begin if not public.bs_is_admin() then raise exception 'Acesso negado'; end if; update public.profiles set bs_coins=greatest(0,coalesce(bs_coins,0)+p_amount) where user_id=p_user_id returning bs_coins into b; if b is null then raise exception 'Jogador não encontrado'; end if; return b; end $$;
grant execute on function public.bs_admin_adjust_coins(uuid,bigint,text) to authenticated;

create or replace function public.bs_admin_confirm_coin_order(p_order_id bigint) returns bigint language plpgsql security definer set search_path=public as $$ declare r public.bs_coin_orders%rowtype; b bigint; begin if not public.bs_is_admin() then raise exception 'Acesso negado'; end if; select * into r from public.bs_coin_orders where id=p_order_id for update; if r.id is null then raise exception 'Pedido não encontrado'; end if; if r.status<>'pending' then raise exception 'Pedido já processado'; end if; update public.profiles set bs_coins=coalesce(bs_coins,0)+r.coins where user_id=r.user_id returning bs_coins into b; update public.bs_coin_orders set status='approved',approved_at=now(),approved_by=auth.uid() where id=p_order_id; return b; end $$;
grant execute on function public.bs_admin_confirm_coin_order(bigint) to authenticated;

