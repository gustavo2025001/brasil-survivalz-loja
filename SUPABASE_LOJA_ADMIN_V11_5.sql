create or replace function public.bs_build_order_items(p_items jsonb, out normalized jsonb, out total_brl numeric, out total_bs bigint)
language plpgsql security definer set search_path=public as $$
declare r jsonb; pid text; qty int; prod jsonb; arr jsonb='[]'::jsonb;
begin
 total_brl:=0; total_bs:=0;
 if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'Carrinho vazio'; end if;
 for r in select * from jsonb_array_elements(p_items) loop
  pid:=r->>'id'; qty:=greatest(1,least(99,coalesce((r->>'qty')::int,1))); prod:=public.bs_catalog()->pid;
  if prod is null then raise exception 'Produto inválido: %',pid; end if;
  total_brl:=total_brl+((prod->>'brl')::numeric*qty); total_bs:=total_bs+((prod->>'bs')::bigint*qty);
  arr:=arr||jsonb_build_array(jsonb_build_object('id',pid,'name',prod->>'name','qty',qty,'brl',prod->>'brl','bs',prod->>'bs'));
 end loop; normalized:=arr;
end $$;

create or replace function public.bs_create_pix_order(p_items jsonb,p_pix_txid text)
returns bigint language plpgsql security definer set search_path=public as $$
declare pr public.profiles%rowtype; norm jsonb; brl numeric; coins bigint; oid bigint;
begin
 if auth.uid() is null then raise exception 'Faça login para finalizar'; end if;
 select * into pr from public.profiles where user_id=auth.uid(); if pr.user_id is null then raise exception 'Perfil não encontrado'; end if;
 select normalized,total_brl,total_bs into norm,brl,coins from public.bs_build_order_items(p_items);
 insert into public.bs_shop_orders(user_id,player_name,steam_id,items,total_brl,total_bs,payment_method,pix_txid,status)
 values(auth.uid(),coalesce(pr.player_name,'Jogador'),coalesce(pr.steam_id,''),norm,brl,coins,'pix',p_pix_txid,'pending') returning id into oid;
 return oid;
end $$;
grant execute on function public.bs_create_pix_order(jsonb,text) to authenticated;

create or replace function public.bs_place_bs_order(p_items jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare pr public.profiles%rowtype; norm jsonb; brl numeric; coins bigint; oid bigint; newbal bigint;
begin
 if auth.uid() is null then raise exception 'Faça login para comprar'; end if;
 select * into pr from public.profiles where user_id=auth.uid() for update; if pr.user_id is null then raise exception 'Perfil não encontrado'; end if;
 select normalized,total_brl,total_bs into norm,brl,coins from public.bs_build_order_items(p_items);
 if coalesce(pr.bs_coins,0)<coins then raise exception 'Saldo insuficiente. Necessário % BS',coins; end if;
 update public.profiles set bs_coins=bs_coins-coins where user_id=auth.uid() returning bs_coins into newbal;
 insert into public.bs_shop_orders(user_id,player_name,steam_id,items,total_brl,total_bs,payment_method,status,approved_at)
 values(auth.uid(),coalesce(pr.player_name,'Jogador'),coalesce(pr.steam_id,''),norm,brl,coins,'bs','approved',now()) returning id into oid;
 return jsonb_build_object('order_id',oid,'new_balance',newbal);
end $$;
grant execute on function public.bs_place_bs_order(jsonb) to authenticated;

